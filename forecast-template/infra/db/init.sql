-- Forecast template: схема БД. Владелец: C#-бэкенд.
-- Совместимо с PostgreSQL 13 (локально postgres:13.1-alpine) и 16 (VM).
-- Выполняется один раз из /docker-entrypoint-initdb.d суперпользователем (POSTGRES_USER)
-- при пустом каталоге данных. Работает и с POSTGRES_DB=forecast, и без него.
-- Пароли ниже — только для локалки (пароль = имя пользователя). На VM их меняет DevOps:
--   ALTER ROLE app PASSWORD '...'; ALTER ROLE ml_reader PASSWORD '...';
-- Этот файл — источник правды схемы: EF Core маппится на него, миграции/EnsureCreated не используем.

\set ON_ERROR_STOP on

-- 1. Роли -------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app') THEN
    CREATE ROLE app LOGIN PASSWORD 'app';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ml_reader') THEN
    CREATE ROLE ml_reader LOGIN PASSWORD 'ml_reader';
  END IF;
END
$$;

-- 2. База -------------------------------------------------------------------
SELECT 'CREATE DATABASE forecast OWNER app'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'forecast')
\gexec
ALTER DATABASE forecast OWNER TO app;
REVOKE ALL ON DATABASE forecast FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE forecast TO app;
GRANT CONNECT ON DATABASE forecast TO ml_reader;

\connect forecast

ALTER SCHEMA public OWNER TO app;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO ml_reader;

-- Все объекты ниже принадлежат app.
SET ROLE app;

-- 3. Таблицы ----------------------------------------------------------------

CREATE TABLE datasets (
    id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    name         text        NOT NULL,
    status       text        NOT NULL DEFAULT 'importing'
                             CHECK (status IN ('importing', 'ready', 'failed')),
    rows         bigint,                    -- строк в observations после импорта
    series_count integer,
    date_from    date,                      -- первая дата с sales IS NOT NULL
    date_to      date,                      -- последняя дата с sales IS NOT NULL (cutoff по умолчанию)
    created_at   timestamptz NOT NULL DEFAULT now(),
    ready_at     timestamptz
);
CREATE INDEX datasets_ready_idx ON datasets (ready_at DESC) WHERE status = 'ready';

-- Ряд = уникальный ключ внутри датасета. Ключевые колонки репетиции: store_nbr, family.
-- На хакатоне ключевые колонки меняются здесь, в UNIQUE и во view ml_observations.
-- attrs: дополнительные атрибуты ряда (city, state, type, cluster ...), необязательны.
CREATE TABLE series (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id uuid    NOT NULL REFERENCES datasets (id) ON DELETE CASCADE,
    store_nbr  integer NOT NULL,
    family     text    NOT NULL,
    attrs      jsonb   NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT series_key_uq UNIQUE (dataset_id, store_nbr, family)
);

-- Наблюдения (~3 млн строк, грузятся COPY BINARY).
-- sales IS NULL — будущая дата с известными признаками (например, строки test.csv).
CREATE TABLE observations (
    series_id   integer          NOT NULL REFERENCES series (id) ON DELETE CASCADE,
    date        date             NOT NULL,
    sales       double precision CHECK (sales >= 0),
    onpromotion integer          CHECK (onpromotion >= 0),
    CONSTRAINT observations_pk PRIMARY KEY (series_id, date)
);

CREATE TABLE jobs (
    id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    kind        text        NOT NULL CHECK (kind IN ('import', 'train')),
    status      text        NOT NULL DEFAULT 'queued'
                            CHECK (status IN ('queued', 'running', 'done', 'failed')),
    dataset_id  uuid        REFERENCES datasets (id) ON DELETE CASCADE,
    params      jsonb       NOT NULL DEFAULT '{}'::jsonb,  -- {"path": "store-sales/train.csv", ...}
    progress    real        CHECK (progress BETWEEN 0 AND 1),
    message     text,
    result      jsonb,                                     -- {"rows":..,"seriesCount":..,"dateFrom":..,"dateTo":..}
    warnings    jsonb       NOT NULL DEFAULT '[]'::jsonb,  -- [{"line":12,"message":"..."}], до 100 шт.
    error       text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    started_at  timestamptz,
    finished_at timestamptz
);
CREATE INDEX jobs_status_idx ON jobs (status, created_at);

CREATE TABLE forecast_runs (
    id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    dataset_id     uuid        NOT NULL REFERENCES datasets (id) ON DELETE CASCADE,
    status         text        NOT NULL DEFAULT 'queued'
                               CHECK (status IN ('queued', 'running', 'done', 'failed')),
    horizon        integer     NOT NULL CHECK (horizon BETWEEN 1 AND 16),
    cutoff_date    date        NOT NULL,
    interval_level real        NOT NULL DEFAULT 0.8,
    model_version  text,
    metrics        jsonb,      -- camelCase как в API: {"rmsle":..,"mae":..,"baselineRmsle":..}
    warnings       jsonb       NOT NULL DEFAULT '[]'::jsonb,
    error          text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    started_at     timestamptz,
    finished_at    timestamptz
);
CREATE INDEX forecast_runs_latest_idx ON forecast_runs (dataset_id, finished_at DESC) WHERE status = 'done';

-- Прогнозы. series_id IS NULL — полный агрегат (сумма всех рядов) от ML.
-- Частичные агрегаты (магазин=all или семейство=all) не храним, API считает их суммой на лету.
CREATE TABLE forecasts (
    id        bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id    uuid             NOT NULL REFERENCES forecast_runs (id) ON DELETE CASCADE,
    series_id integer          REFERENCES series (id) ON DELETE CASCADE,
    date      date             NOT NULL,
    yhat      double precision NOT NULL CHECK (yhat >= 0),
    lo        double precision,
    hi        double precision,
    CHECK (lo IS NULL OR lo <= yhat),
    CHECK (hi IS NULL OR hi >= yhat)
);
-- Postgres 13 не умеет UNIQUE NULLS NOT DISTINCT, поэтому два частичных индекса.
CREATE UNIQUE INDEX forecasts_series_uq    ON forecasts (run_id, series_id, date) WHERE series_id IS NOT NULL;
CREATE UNIQUE INDEX forecasts_aggregate_uq ON forecasts (run_id, date)            WHERE series_id IS NULL;

-- 4. View для ML ------------------------------------------------------------
-- Единственный объект, доступный ml_reader. Ключи ряда — колонками.
-- История: sales IS NOT NULL; будущие известные признаки: sales IS NULL.
CREATE VIEW ml_observations AS
SELECT s.dataset_id,
       s.store_nbr,
       s.family,
       o.date,
       o.sales,
       o.onpromotion
FROM observations o
JOIN series s ON s.id = o.series_id;

COMMENT ON VIEW ml_observations IS
  'Read-only история для ML. Фильтровать по dataset_id. sales IS NULL = будущие известные признаки.';

RESET ROLE;

-- 5. Права ml_reader: только SELECT на view ---------------------------------
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM ml_reader;
GRANT SELECT ON ml_observations TO ml_reader;
ALTER ROLE ml_reader SET default_transaction_read_only = on;
